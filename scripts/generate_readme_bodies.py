"""Print all measured tables, or use --main to refresh only README.md's selection."""

import argparse
from contextlib import redirect_stdout
from io import StringIO
from pathlib import Path
import re
import sys

import pandas as pd

from plot_config import files
from utils import load_df, draw_table, HEADER, TITLE, NL, NOTES


REPO_ROOT = Path(__file__).resolve().parents[1]
README_IMPLEMENTATION = "readme_implementation"
BEGIN_MARKER = "<!-- BEGIN GENERATED BENCHMARK TABLES -->"
END_MARKER = "<!-- END GENERATED BENCHMARK TABLES -->"


def format_power_of_two(value):
  value = int(value)
  if value > 0 and value & (value - 1) == 0:
    return f"$2^{{{value.bit_length() - 1}}}$"
  return str(value)


def format_batch_size(value):
  value = int(value)
  for unit, size in [("M", 1 << 20), ("K", 1 << 10)]:
    if value > 0 and value % size == 0:
      return f"{value // size}{unit}"
  return str(value)


def readme_implementation_label(implementation, benchmark_type=None):
  labels = {
    "Signal": "Signal-Old",
    "Signal_Sharded": "Signal-Old-Sharded",
    "Signal_Jasmine": "Signal-Jasmine",
    "Signal_Jasmine_Sharded": "Signal-Jasmine-Sharded",
    "olabs_oram_sharded": "olabs_umap_sharded",
    "olabs_oram_shortkv": "olabs_umap_shortkv",
  }
  if implementation == "olabs_oram" and benchmark_type == "UnorderedMap":
    return "olabs_umap"
  return labels.get(implementation, implementation)


def add_readme_columns(data):
  data = data.copy()
  for column in ["Shards", "Batch_size"]:
    if column not in data:
      data[column] = pd.NA

  def label(row):
    name = readme_implementation_label(row["implementation"], row["benchmark_type"])
    config = []
    if pd.notna(row["Shards"]):
      config.append(f"S={int(row['Shards'])}")
    return name + (f" ({', '.join(config)})" if config else "")

  data[README_IMPLEMENTATION] = data.apply(label, axis=1)
  return data


def draw_readme_table(data, x_name, metric, *, columns=README_IMPLEMENTATION, highlight=-1):
  """Never silently average distinct measurements into the same table cell."""
  if metric not in data:
    return
  data = data.dropna(subset=[x_name, metric]).copy()
  if data.empty:
    NOTES("No reported measurements.\n")
    return
  duplicates = data.duplicated([x_name, columns], keep=False)
  if duplicates.any():
    conflicting = data.loc[duplicates, [x_name, columns, metric]]
    raise ValueError(f"Ambiguous table cells for {metric}:\n{conflicting.to_string(index=False)}")
  column_order = list(data[columns].drop_duplicates())
  data = data.sort_values(x_name, kind="stable")
  data[x_name] = data[x_name].map(format_power_of_two)
  order = {} if columns == README_IMPLEMENTATION else {"col_order": column_order}
  draw_table(data, x_name, metric, columns=columns, highlight=highlight, **order)
  NL()


def payload_groups(data):
  return data.groupby(["Key_bytes", "Value_bytes"], sort=True)


def payload_title(key_bytes, value_bytes):
  return f"{int(key_bytes)}B keys, {int(value_bytes)}B values"


def draw_read_metrics(data, latency, throughput, *, batch=False):
  TITLE("Batch read latency (us/batch)" if batch else "Read latency (us/query)")
  draw_readme_table(data, "N", latency)
  TITLE("Read throughput (queries/s)")
  draw_readme_table(data, "N", throughput, highlight=1)


def generate_tables(data, source_files):
  if data.empty:
    raise ValueError("No benchmark measurements found in the selected result files")
  data = add_readme_columns(data)

  NOTES("<!-- Generated by `uv run scripts/generate_readme_bodies.py --write-readme`. -->\n")
  NOTES("<details>\n<summary>Source result files</summary>\n")
  for path in source_files:
    NOTES(f"- `{Path(path).name}`")
  NOTES("\n</details>\n")

  for benchmark_type, title in [("NRORAM", "Non-Recursive ORAM (NRORAM)"),
                                ("RORAM", "Recursive ORAM (RORAM)")]:
    HEADER(title)
    oram = data.loc[data["benchmark_type"] == benchmark_type]
    if benchmark_type == "NRORAM":
      # Keep Par32 out of the README comparison, including historical results.
      oram = oram.loc[oram["implementation"] != "sonic_par32"]
    for (key_bytes, value_bytes), group in payload_groups(oram):
      NOTES(f"<details>\n<summary>{payload_title(key_bytes, value_bytes)}</summary>\n")
      draw_read_metrics(group, "Read_latency_us", "Read_throughput_qps")
      NOTES("</details>\n")

  umap = data.loc[data["benchmark_type"] == "UnorderedMap"]
  HEADER("Unordered Map - Single Queries")
  for (key_bytes, value_bytes), group in payload_groups(
      umap.loc[umap["Batch_size"].isna() & umap["Shards"].isna()]):
    NOTES(f"<details>\n<summary>{payload_title(key_bytes, value_bytes)}</summary>\n")
    draw_read_metrics(group, "Get_latency_us", "Get_throughput_qps")
    NOTES("</details>\n")

  batched = umap.loc[umap["Batch_size"].notna()]
  HEADER("Unordered Map - Batched Queries")
  NOTES("Each comparison fixes the batch size. Latency is for the whole batch, not one query.\n")
  for (key_bytes, value_bytes), payload in payload_groups(batched):
    for batch_size, group in payload.groupby("Batch_size", sort=True):
      NOTES(f"<details>\n<summary>{payload_title(key_bytes, value_bytes)}, "
            f"{format_batch_size(batch_size)} queries/batch</summary>\n")
      draw_read_metrics(group, "Get_latency_us", "Get_throughput_qps", batch=True)
      NOTES("</details>\n")

  HEADER("Unordered Map - Scaling with Batch Size")
  for (key_bytes, value_bytes), payload in payload_groups(batched):
    for implementation, group in payload.groupby(README_IMPLEMENTATION, sort=True):
      if group["Batch_size"].nunique() < 2:
        continue
      group = group.sort_values("Batch_size").copy()
      group["Batch"] = group["Batch_size"].map(lambda value: f"B={format_batch_size(value)}")
      NOTES(f"<details>\n<summary>{implementation}: "
            f"{payload_title(key_bytes, value_bytes)}</summary>\n")
      TITLE("Read throughput (queries/s), by batch size")
      draw_readme_table(group, "N", "Get_throughput_qps", columns="Batch", highlight=1)
      TITLE("Batch read latency (us/batch), by batch size")
      draw_readme_table(group, "N", "Get_latency_us", columns="Batch")
      NOTES("</details>\n")

  # Load-balancer cost is measured separately. Match its exact payload and shard
  # configuration; do not reuse an unrelated 8B-value measurement for every map.
  lb = data.loc[data["benchmark_type"] == "LOADBALANCE"]
  lb_olabs = lb.loc[lb["implementation"] == "olabs_oram"]
  if not lb_olabs.empty:
    join_columns = ["Key_bytes", "Value_bytes", "Shards", "Batch_size"]
    # Batch_size is absent in LOADBALANCE reports, but exists as a nullable
    # column in the combined frame. Drop it before renaming B.
    lb_costs = lb_olabs.drop(columns="Batch_size").rename(
      columns={"B": "Batch_size", "Latency_us": "LB_latency_us"})
    cost = batched.loc[batched["implementation"] == "olabs_oram_sharded"].merge(
      lb_costs[join_columns + ["LB_latency_us"]], on=join_columns,
      how="left", validate="many_to_one")
    if not cost.empty:
      total = cost["Get_burst_latency_us"] + cost["Get_writeback_latency_us"]
      cost["Load_balance_percent"] = 100 * cost["LB_latency_us"] / total.where(total > 0)
      HEADER("Unordered Map - Query Cost Breakdown")
      NOTES("Estimated load-balancing share (%): separately measured matching-payload "
            "load-balancer latency divided by the map's burst + writeback latency.\n")
      for (key_bytes, value_bytes), payload in payload_groups(cost):
        for implementation, group in payload.groupby(README_IMPLEMENTATION, sort=True):
          group = group.sort_values("Batch_size").copy()
          group["Batch"] = group["Batch_size"].map(lambda value: f"B={format_batch_size(value)}")
          NOTES(f"<details>\n<summary>{implementation}: "
                f"{payload_title(key_bytes, value_bytes)}</summary>\n")
          draw_readme_table(group, "N", "Load_balance_percent", columns="Batch", highlight=0)
          NOTES("</details>\n")

  HEADER("Load Balancer")
  for (key_bytes, value_bytes), group in payload_groups(lb):
    NOTES(f"<details>\n<summary>{payload_title(key_bytes, value_bytes)}</summary>\n")
    TITLE("Batch latency (us/batch), by batch size B")
    draw_readme_table(group, "B", "Latency_us")
    TITLE("Throughput (queries/s), by batch size B")
    draw_readme_table(group, "B", "Throughput_qps", highlight=1)
    NOTES("</details>\n")


def readme_parts(text, path):
  if (text.count(BEGIN_MARKER) != 1 or text.count(END_MARKER) != 1
      or text.index(BEGIN_MARKER) > text.index(END_MARKER)):
    raise ValueError(f"{path}: expected exactly one ordered generated-table marker pair")
  before, rest = text.split(BEGIN_MARKER, 1)
  body, after = rest.split(END_MARKER, 1)
  return before, body, after


def table_spans(body):
  """Index our Markdown tables by section, details summary, and metric title."""
  lines = body.splitlines(keepends=True)
  offsets = [0]
  for line in lines:
    offsets.append(offsets[-1] + len(line))
  tables = {}
  section = summary = metric = ""
  index = 0
  while index < len(lines):
    line = lines[index].strip()
    if line.startswith("### "):
      section = line[4:]
      summary = metric = ""
    elif line.startswith("<summary>") and line.endswith("</summary>"):
      summary = line[len("<summary>"):-len("</summary>")]
      metric = ""
    elif line == "</details>":
      summary = metric = ""
    elif line.startswith("##### "):
      metric = line[6:]
    elif line.startswith("|"):
      start = index
      while index < len(lines) and lines[index].strip().startswith("|"):
        index += 1
      key = (section, summary, metric)
      if (not section or not summary or index - start < 2
          or not re.fullmatch(r"\|(?:\s*:?-+:?\s*\|)+", lines[start + 1].strip())):
        raise ValueError(f"Malformed benchmark table: {' / '.join(key)}")
      if key in tables:
        raise ValueError(f"Duplicate benchmark table: {' / '.join(key)}")
      tables[key] = (offsets[start], offsets[index])
      continue
    index += 1
  return tables


def preserve_header_notes(table, template):
  """Keep trailing footnote stars such as README's h2o2* header."""
  labels = [cell.strip() for cell in template.splitlines()[0].split("|")]
  aliases = {label.rstrip("*"): label for label in labels if label.endswith("*")}
  header, newline, rest = table.partition("\n")
  cells = [cell.replace(cell.strip(), aliases[cell.strip()], 1)
           if cell.strip() in aliases else cell for cell in header.split("|")]
  return "|".join(cells) + newline + rest


def refresh_main_tables(generated, template):
  """Replace only selected tables and provenance; retain README order and prose."""
  available = table_spans(generated)
  selected = table_spans(template)
  if not selected:
    raise ValueError("README.md contains no benchmark tables to refresh")
  replacements = []
  for key, (start, end) in selected.items():
    if key not in available:
      raise ValueError(f"No generated table matches README selection: {' / '.join(key)}")
    new_start, new_end = available[key]
    table = preserve_header_notes(generated[new_start:new_end], template[start:end])
    replacements.append((start, end, table))

  # Source filenames must describe the refreshed values, not the previous run.
  sources = re.compile(r"<details>\s*<summary>Source result files</summary>.*?</details>", re.S)
  old_sources = list(sources.finditer(template))
  new_sources = list(sources.finditer(generated))
  if len(old_sources) > 1 or (old_sources and len(new_sources) != 1):
    raise ValueError("Expected an unambiguous source result files block")
  if old_sources:
    old = old_sources[0]
    replacements.append((old.start(), old.end(), new_sources[0].group()))
  for start, end, replacement in sorted(replacements, reverse=True):
    template = template[:start] + replacement + template[end:]
  template = template.replace(
    "Generated by `uv run scripts/generate_readme_bodies.py --write-readme`.",
    "Generated by `uv run scripts/generate_readme_bodies.py --main --write-readme`.")
  return template.strip("\n") + "\n"


def update_readme(body, path, *, expected=None):
  text = path.read_text()
  if expected is not None and text != expected:
    raise ValueError(f"{path}: changed during generation; not overwriting concurrent edits")
  before, _, after = readme_parts(text, path)
  updated = f"{before}{BEGIN_MARKER}\n\n{body.rstrip()}\n\n{END_MARKER}{after}"
  if updated != text:
    path.write_text(updated)


def main():
  parser = argparse.ArgumentParser(description=__doc__)
  parser.add_argument("--main", action="store_true",
                      help="refresh only tables already in README.md; keep their order and notes")
  parser.add_argument("--write-readme", action="store_true",
                      help="replace the marked README.md section (use --main to keep its selection)")
  args = parser.parse_args()
  try:
    if not files:
      raise ValueError("No benchmark result files found")
    readme_path = REPO_ROOT / "README.md"
    original = readme_path.read_text() if args.main else None
    if args.main:
      _, template, _ = readme_parts(original, readme_path)
    output = StringIO()
    with redirect_stdout(output):
      # Deliberately do not call augmentP: its synthesized H2O2 OMAP and Signal
      # payload-conversion rows are estimates, not measurements from this run.
      generate_tables(load_df(), files)
    body = refresh_main_tables(output.getvalue(), template) if args.main else output.getvalue()
    if args.write_readme:
      update_readme(body, readme_path, expected=original)
      print("Updated README.md benchmark tables.", file=sys.stderr)
    else:
      print(body, end="")
  except (OSError, ValueError) as error:
    parser.exit(1, f"{error}\n")


if __name__ == "__main__":
  main()
